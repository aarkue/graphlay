// Embeds the wasm as base64 so the package loads in any bundler or runtime without asset config.
// The glue's `new URL(...)` default goes, since bundlers that see it emit the wasm a second time.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "pkg");
const wasmPath = join(pkg, "graphlay_bg.wasm");
const gluePath = join(pkg, "graphlay.js");

if (!existsSync(wasmPath)) {
  throw new Error(`${wasmPath} is missing: run \`pnpm build:wasm\` first`);
}

const marker = "new URL('graphlay_bg.wasm', import.meta.url)";
const patched = "(() => { throw new Error('graphlay: no wasm source; pass one to load()'); })()";
const glue = readFileSync(gluePath, "utf8");
if (glue.includes(marker)) {
  writeFileSync(gluePath, glue.replace(marker, patched));
} else if (!glue.includes(patched)) {
  throw new Error(`${gluePath}: the wasm-pack glue changed shape, update inline-wasm.mjs`);
}

const b64 = readFileSync(wasmPath).toString("base64");
writeFileSync(
  join(pkg, "graphlay_inline.js"),
  `// Generated by scripts/inline-wasm.mjs: graphlay_bg.wasm as base64.\nexport const wasmBase64 = "${b64}";\n`,
);
writeFileSync(join(pkg, "graphlay_inline.d.ts"), "export declare const wasmBase64: string;\n");
console.log(`inline-wasm: ${(b64.length / 1024).toFixed(0)} KB of base64`);
