// Writes src/types.ts from the JSON schemas the engine prints (`graphlay schema`), so the
// TypeScript types follow the Rust types without a hand-written copy.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..", "..");
const text = execFileSync("cargo", ["run", "-q", "-p", "graphlay-cli", "--", "schema"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const schemas = JSON.parse(text);

// A `$ref` with a sibling description would be inlined as a copy per field. Moving the ref into
// `allOf` keeps the description as the field's comment and the type shared.
function liftRefSiblings(node) {
  if (Array.isArray(node)) return node.map(liftRefSiblings);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) out[k] = liftRefSiblings(v);
  if ("$ref" in out && Object.keys(out).length > 1) {
    const { $ref, ...rest } = out;
    return { allOf: [{ $ref }], ...rest };
  }
  return out;
}

// One schema with every type under $defs, so shared types such as Size come out once.
const defs = {};
const properties = {};
for (const [name, schema] of Object.entries(schemas)) {
  const { $schema, $defs, ...own } = liftRefSiblings(schema);
  Object.assign(defs, $defs);
  defs[name] = own;
  properties[name] = { $ref: `#/$defs/${name}` };
}
const combined = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  title: "GraphlayTypes",
  type: "object",
  properties,
  required: Object.keys(properties),
  additionalProperties: false,
  $defs: defs,
};

let out = await compile(combined, "GraphlayTypes", {
  bannerComment: "// Generated by scripts/gen-types.mjs from `graphlay schema`. Do not edit.",
  additionalProperties: false,
  unreachableDefinitions: true,
});
writeFileSync(join(here, "..", "src", "types.ts"), out);
console.log(`gen-types: ${Object.keys(defs).length} types`);
